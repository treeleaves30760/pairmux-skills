"""Shared, cross-platform helpers for the pairmux-skills eval scenarios.

Every scenario's control scripts (setup.py, check.py, golden.py, human.py) import this module and
run under the same interpreter as the runner, isolated (``python -I``), on macOS, Linux and native
Windows alike. It replaces the former POSIX-only lib.sh.

Isolated mode does not put the script's directory on sys.path, so control scripts locate this file
explicitly (it always sits two directories above them: evals/scenarios/<ID>/<script>.py):

    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    import evallib

The env file a setup writes (default <scenario>/env.sh, or $PAIRMUX_EVAL_ENV_FILE) is data, never
code for this module: it holds only ``export NAME=<POSIX-quoted value>`` lines (plus comments and a
fixed proxy block), so a POSIX shell can still source it for manual runs while Python parses it
without evaluating anything.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import time

IS_WINDOWS = os.name == "nt"
EVALS_DIR = Path(__file__).resolve().parent
# What a scenario's terminal commands call the interpreter. Windows installs `python` (a
# `python3` there is usually the Microsoft Store stub); POSIX keeps the historical `python3`.
PYTHON = "python" if IS_WINDOWS else "python3"
EXE_SUFFIX = ".exe" if IS_WINDOWS else ""

ENV_FILE_HEADER = (
    "# shellcheck shell=sh\n"
    "# Generated by setup. Data only: export NAME=VALUE lines. POSIX shells may source it for a\n"
    "# manual run; the Python checker parses it without evaluating anything.\n"
)
_PROXY_BLOCK = (
    'if [ -n "${PAIRMUX_EVAL_PROXY_DIR:-}" ]; then\n'
    '  export PATH="${PAIRMUX_EVAL_PROXY_DIR}:$PATH"\n'
    "fi\n"
    'if [ -n "${PAIRMUX_EVAL_PROXY_BIN:-}" ]; then\n'
    '  export PAIRMUX_BIN="$PAIRMUX_EVAL_PROXY_BIN"\n'
    "fi\n"
)
_ENV_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_ANSI = re.compile(rb"\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)|\x1b[@-Z\\-_]")


# ---- locations ----------------------------------------------------------------------------------

def script_dir(script_file: str) -> Path:
    return Path(script_file).resolve().parent


def scenario_dir(script_file: str) -> Path:
    """The fixture directory: $PAIRMUX_EVAL_SCENARIO_DIR (runner/worktree) or the script's own."""
    configured = os.environ.get("PAIRMUX_EVAL_SCENARIO_DIR")
    return Path(configured) if configured else script_dir(script_file)


def env_file_path(scen_dir: Path) -> Path:
    configured = os.environ.get("PAIRMUX_EVAL_ENV_FILE")
    return Path(configured) if configured else Path(scen_dir) / "env.sh"


def is_executable(path: str | os.PathLike[str] | None) -> bool:
    if not path:
        return False
    candidate = Path(path)
    return candidate.is_file() and (IS_WINDOWS or os.access(candidate, os.X_OK))


def sibling_pairmux_candidates(base: Path = EVALS_DIR) -> list[Path]:
    """A built sibling ../pairmux checkout (bin/pairmux, bin/pairmux.exe on Windows)."""
    names = ("pairmux.exe", "pairmux") if IS_WINDOWS else ("pairmux",)
    return [root / "pairmux" / "bin" / name
            for root in (base.parent.parent, base.parent.parent.parent) for name in names]


def resolve_pairmux_bin() -> str | None:
    """Honor an explicit runner value, then PATH, then a sibling build.

    Paths are made absolute but symlinks are NOT resolved (as lib.sh did): the setup prepends
    this binary's directory to PATH, and a `uv tool` pairmux resolves into its private venv
    bin/, whose python3 would then shadow the host interpreter inside the fixtures."""
    for name in ("PAIRMUX_REAL_BIN", "PAIRMUX_BIN"):
        configured = os.environ.get(name, "")
        if is_executable(configured):
            return str(Path(configured).absolute())
    found = shutil.which("pairmux")
    if found:
        return str(Path(found).absolute())
    for candidate in sibling_pairmux_candidates():
        if is_executable(candidate):
            return str(candidate.absolute())
    return None


def pairmux_bin() -> str:
    return os.environ.get("PAIRMUX_BIN") or "pairmux"


# ---- endpoint identity (mirrors pairmux internal/state + internal/rundir) -----------------------

def _canonical(root: str) -> str:
    """filepath.Abs + Clean + EvalSymlinks (left unresolved when the path does not exist)."""
    root = os.path.normpath(os.path.abspath(root))
    if os.path.exists(root):
        root = os.path.realpath(root)
    return root


def _uid() -> int:
    return os.getuid() if hasattr(os, "getuid") else -1


def effective_backend(env: dict[str, str] | None = None) -> str:
    """The multiplexer pairmux will choose: always builtin on Windows; PAIRMUX_BACKEND when set;
    otherwise tmux when it is installed (pairmux also reverts to builtin for tmux < 3.2, which
    the evals do not support as a tmux host)."""
    env = os.environ if env is None else env
    if IS_WINDOWS:
        return "builtin"
    chosen = env.get("PAIRMUX_BACKEND", "").strip().lower()
    if chosen in {"builtin", "native", "internal"}:
        return "builtin"
    if chosen == "tmux":
        return "tmux"
    return "tmux" if shutil.which("tmux", path=env.get("PATH")) else "builtin"


def builtin_runtime_dir(env: dict[str, str] | None = None) -> str:
    env = os.environ if env is None else env
    if IS_WINDOWS:
        root = env.get("PAIRMUX_TMPDIR") or os.path.join(
            env.get("LOCALAPPDATA") or os.path.join(env.get("USERPROFILE", ""), "AppData", "Local"),
            "pairmux")
        return os.path.join(_canonical(root), "run")
    root = env.get("PAIRMUX_TMPDIR") or env.get("TMUX_TMPDIR") or "/tmp"
    return os.path.join(_canonical(root), f"pairmux-{_uid()}")


def endpoint_identity(socket: str, env: dict[str, str] | None = None, backend: str | None = None) -> str:
    env = os.environ if env is None else env
    socket = socket or "pairmux"
    if (backend or effective_backend(env)) == "builtin":
        return "builtin:" + os.path.join(builtin_runtime_dir(env), socket)
    tmux_root = _canonical(env.get("TMUX_TMPDIR") or "/tmp")
    return os.path.join(tmux_root, f"tmux-{_uid()}", socket)


def state_namespace(state_root: str | os.PathLike[str], socket: str,
                    env: dict[str, str] | None = None, backend: str | None = None) -> Path:
    """pairmux's per-endpoint state namespace: <state>/.sockets/sha256(endpoint identity)."""
    digest = hashlib.sha256(endpoint_identity(socket, env, backend).encode()).hexdigest()
    return Path(state_root) / ".sockets" / digest


# ---- env file -----------------------------------------------------------------------------------

def write_env_file(path: Path, values: dict[str, str], path_prepend: str) -> None:
    lines = [ENV_FILE_HEADER]
    for name, value in values.items():
        if not _ENV_NAME.fullmatch(name):
            raise ValueError(f"invalid environment name: {name!r}")
        lines.append(f"export {name}={shlex.quote(value)}\n")
    # POSIX-sourceable PATH prepend; the separator is the platform's so Python can apply it too.
    lines.append(f"export PATH={shlex.quote(path_prepend)}{os.pathsep}\"$PATH\"\n")
    lines.append(_PROXY_BLOCK)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(lines))


def parse_env_file(path: str | os.PathLike[str]) -> tuple[dict[str, str], list[str]]:
    """Return (exports, PATH prepends) without evaluating anything. Unknown lines are ignored."""
    exports: dict[str, str] = {}
    prepends: list[str] = []
    try:
        text = Path(path).read_text(encoding="utf-8")
    except FileNotFoundError:
        return exports, prepends
    for line in text.splitlines():
        stripped = line.strip()
        # Top-level lines only: the indented proxy block is applied by load_env itself.
        if not line.startswith("export ") or "${" in stripped:
            continue
        try:
            words = shlex.split(stripped[len("export "):], posix=True)
        except ValueError:
            continue
        if len(words) != 1 or "=" not in words[0]:
            continue
        name, value = words[0].split("=", 1)
        if not _ENV_NAME.fullmatch(name):
            continue
        if name == "PATH":
            suffix = os.pathsep + "$PATH"
            if value.endswith(suffix):
                prepends.append(value[: -len(suffix)])
            continue
        exports[name] = value
    return exports, prepends


def load_env(env_file: str | os.PathLike[str] | None = None, *, scen_dir: Path | None = None) -> dict[str, str]:
    """Apply an env file to os.environ the way sourcing it would, and return os.environ."""
    if env_file is None:
        env_file = env_file_path(scen_dir if scen_dir is not None else Path.cwd())
    exports, prepends = parse_env_file(env_file)
    os.environ.update(exports)
    for directory in prepends:
        os.environ["PATH"] = directory + os.pathsep + os.environ.get("PATH", "")
    proxy_dir = os.environ.get("PAIRMUX_EVAL_PROXY_DIR")
    if proxy_dir:
        os.environ["PATH"] = proxy_dir + os.pathsep + os.environ.get("PATH", "")
    proxy_bin = os.environ.get("PAIRMUX_EVAL_PROXY_BIN")
    if proxy_bin:
        os.environ["PAIRMUX_BIN"] = proxy_bin
    return dict(os.environ)


# ---- endpoint lifecycle -------------------------------------------------------------------------

def stop_endpoint(socket: str, env: dict[str, str] | None = None, backend: str | None = None) -> None:
    """Best-effort: stop every terminal on one eval-owned endpoint (never any other server)."""
    env = dict(os.environ if env is None else env)
    if not socket:
        return
    if (backend or effective_backend(env)) == "tmux":
        tmux = shutil.which("tmux", path=env.get("PATH"))
        if tmux:
            subprocess.run([tmux, "-L", socket, "kill-server"], env=env, stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, timeout=15, check=False)
        return
    # The built-in server exits on its own once it has had no terminals for a short while.
    binary = env.get("PAIRMUX_REAL_BIN") or env.get("PAIRMUX_BIN") or resolve_pairmux_bin()
    if binary and is_executable(binary):
        env["PAIRMUX_SOCKET"] = socket
        try:
            subprocess.run([binary, "--socket", socket, "kill", "--all"], env=env,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30, check=False)
        except subprocess.TimeoutExpired:
            pass


def remove_tree(path: str | os.PathLike[str], attempts: int = 20) -> None:
    """rmtree that tolerates Windows' brief sharing violations after a process exits."""
    target = Path(path)
    for attempt in range(attempts):
        if not os.path.lexists(target):
            return
        try:
            shutil.rmtree(target)
            return
        except FileNotFoundError:
            return
        except OSError:
            if attempt == attempts - 1:
                raise
            time.sleep(0.1)


def setup(scen_dir: Path, scenario_id: str) -> dict[str, str]:
    """Write the env file, apply it to this process, and reset the eval-owned state directory."""
    scen_dir = Path(scen_dir)
    binary = resolve_pairmux_bin()
    if binary is None:
        raise SystemExit("error: pairmux binary not found. Install pairmux, or build the sibling "
                         "../pairmux repo.")
    state = Path(os.environ.get("PAIRMUX_EVAL_STATE_DIR") or scen_dir / "state").expanduser().resolve()
    control = os.environ.get("PAIRMUX_EVAL_CONTROL_ROOT", "")
    allowed = {(scen_dir / "state").resolve()}
    if control:
        allowed.add((Path(control) / "runtime" / "state").resolve())
    if state not in allowed:
        raise SystemExit(f"error: refusing to reset unexpected eval state directory: {state}")
    env_file = env_file_path(scen_dir)
    socket = os.environ.get("PAIRMUX_EVAL_SOCKET") or f"pmx-eval-{scenario_id}"
    tmux_tmp = os.environ.get("TMPDIR") or ("" if IS_WINDOWS else "/tmp")
    values = {"PAIRMUX_SOCKET": socket, "PAIRMUX_STATE_DIR": str(state)}
    if not IS_WINDOWS:
        values["TMUX_TMPDIR"] = tmux_tmp
    values["PAIRMUX_BIN"] = binary
    if IS_WINDOWS or os.environ.get("PAIRMUX_BACKEND"):
        values["PAIRMUX_BACKEND"] = "builtin" if IS_WINDOWS else os.environ["PAIRMUX_BACKEND"]
    if os.environ.get("PAIRMUX_TMPDIR"):
        values["PAIRMUX_TMPDIR"] = os.environ["PAIRMUX_TMPDIR"]
    probe = dict(os.environ, **values)
    values["PAIRMUX_STATE_NAMESPACE"] = str(state_namespace(state, socket, probe))
    write_env_file(env_file, values, str(Path(binary).parent))
    load_env(env_file)
    stop_endpoint(socket)
    remove_tree(state)
    state.mkdir(parents=True)
    if IS_WINDOWS and not os.environ.get("PAIRMUX_EVAL_CONTROL_ROOT"):
        print(manual_hint(scen_dir))  # a manual run cannot `source` env.sh in PowerShell
    return dict(os.environ)


def manual_hint(scen_dir: Path) -> str:
    """How a person runs an agent by hand against this fixture (printed by setup)."""
    env_file = env_file_path(scen_dir)
    if IS_WINDOWS:
        exports, prepends = parse_env_file(env_file)
        lines = [f"$env:{name} = '{value.replace(chr(39), chr(39) * 2)}'" for name, value in exports.items()
                 if not name.startswith("PAIRMUX_EVAL_")]
        lines += [f"$env:PATH = '{p}' + [IO.Path]::PathSeparator + $env:PATH" for p in prepends]
        return "PowerShell environment for a manual run:\n  " + "\n  ".join(lines)
    return f"For a manual run: . {shlex.quote(str(env_file))}"


# ---- process helpers ----------------------------------------------------------------------------

def python_argv(script: str | os.PathLike[str], *args: str) -> list[str]:
    """Run another trusted Python control script with this same interpreter, isolated."""
    return [sys.executable, "-I", str(script), *args]


def pmx(*args: str, check: bool = True, capture: bool = False, timeout: float = 300,
        env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    """Run the configured pairmux binary (the golden solutions' `pairmux ...`)."""
    completed = subprocess.run([pairmux_bin(), *args], env=env, text=True, encoding="utf-8",
                               errors="replace", capture_output=capture, timeout=timeout, check=False)
    if check and completed.returncode != 0:
        detail = (completed.stdout or "") + (completed.stderr or "") if capture else ""
        raise SystemExit(f"pairmux {' '.join(args)} exited {completed.returncode}\n{detail}")
    return completed


def pmx_json(*args: str, timeout: float = 300) -> dict[str, object]:
    completed = pmx("--json", *args, check=False, capture=True, timeout=timeout)
    try:
        payload = json.loads(completed.stdout)
    except json.JSONDecodeError:
        raise SystemExit(f"pairmux --json {' '.join(args)} returned non-JSON output:\n"
                         f"{completed.stdout}{completed.stderr}") from None
    return payload if isinstance(payload, dict) else {}


def spawn_detached(argv: list[str], *, log_path: Path, cwd: Path | None = None,
                   env: dict[str, str] | None = None) -> subprocess.Popen[bytes]:
    """Start a background companion (scripted human) that outlives this setup process."""
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "ab") as log:
        kwargs: dict[str, object] = {}
        if IS_WINDOWS:
            kwargs["creationflags"] = (subprocess.CREATE_NEW_PROCESS_GROUP
                                       | getattr(subprocess, "DETACHED_PROCESS", 0x8)
                                       | getattr(subprocess, "CREATE_NO_WINDOW", 0))
        else:
            kwargs["start_new_session"] = True
        return subprocess.Popen(argv, cwd=cwd, env=env, stdin=subprocess.DEVNULL, stdout=log,
                                stderr=subprocess.STDOUT, close_fds=True, **kwargs)


def terminate_pid(pid: int) -> None:
    """Best-effort SIGTERM (TerminateProcess on Windows) of a companion this eval started."""
    if pid <= 1:
        return
    try:
        if IS_WINDOWS:
            import ctypes

            kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
            handle = kernel32.OpenProcess(0x0001, False, pid)  # PROCESS_TERMINATE
            if handle:
                try:
                    kernel32.TerminateProcess(handle, 1)
                finally:
                    kernel32.CloseHandle(handle)
        else:
            import signal

            os.kill(pid, signal.SIGTERM)
    except (OSError, ValueError):
        pass


def pid_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    if IS_WINDOWS:
        import ctypes

        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        handle = kernel32.OpenProcess(0x1000, False, pid)  # PROCESS_QUERY_LIMITED_INFORMATION
        if not handle:
            return False
        try:
            code = ctypes.c_ulong()
            return bool(kernel32.GetExitCodeProcess(handle, ctypes.byref(code))) and code.value == 259
        finally:
            kernel32.CloseHandle(handle)
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


# ---- check helpers ------------------------------------------------------------------------------

def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)
    raise SystemExit(1)


def passed(message: str = "") -> None:
    print("PASS" + (f": {message}" if message else ""))
    raise SystemExit(0)


def _read_bytes(path: Path) -> bytes | None:
    try:
        return path.read_bytes()
    except OSError:
        return None


def _contains(data: bytes | None, needle: str) -> bool:
    if data is None:
        return False
    encoded = needle.encode("utf-8")
    if encoded in data:
        return True
    # ConPTY re-renders the screen, so a line may arrive split by cursor/erase sequences.
    return IS_WINDOWS and encoded in _ANSI.sub(b"", data)


def _namespaces() -> list[Path]:
    state = Path(os.environ.get("PAIRMUX_STATE_DIR", ""))
    found: list[Path] = []
    advertised = os.environ.get("PAIRMUX_STATE_NAMESPACE")
    if advertised:
        found.append(Path(advertised))
    socket = os.environ.get("PAIRMUX_SOCKET")
    if socket and str(state):
        computed = state_namespace(state, socket)
        if computed not in found:
            found.append(computed)
    return found


def terminal_dir(terminal: str) -> Path:
    """One terminal's state dir under the namespaced layout, the legacy layout, or (for an eval's
    private single-endpoint state root) the only namespace that has it."""
    state = Path(os.environ.get("PAIRMUX_STATE_DIR", ""))
    for namespace in _namespaces():
        if (namespace / terminal).is_dir():
            return namespace / terminal
    legacy = state / terminal
    if legacy.is_dir():
        return legacy
    matches = sorted((state / ".sockets").glob(f"*/{terminal}")) if str(state) else []
    matches = [match for match in matches if match.is_dir()]
    if len(matches) == 1:
        return matches[0]
    return legacy


def journal_has(terminal: str, needle: str) -> bool:
    return _contains(_read_bytes(terminal_dir(terminal) / "raw.log"), needle)


def _all_journals() -> list[Path]:
    state = Path(os.environ.get("PAIRMUX_STATE_DIR", "") or "/nonexistent")
    paths: list[Path] = []
    for namespace in _namespaces():
        paths.extend(sorted(namespace.glob("*/raw.log")))
    paths.extend(sorted(state.glob("*/raw.log")))
    paths.extend(sorted(state.glob(".sockets/*/*/raw.log")))
    unique: list[Path] = []
    for path in paths:
        if path not in unique:
            unique.append(path)
    return unique


def any_journal_has(needle: str) -> bool:
    return any(_contains(_read_bytes(path), needle) for path in _all_journals() if path.is_file())


def index_has(terminal: str, needle: str) -> bool:
    return _contains(_read_bytes(terminal_dir(terminal) / "index.jsonl"), needle)


def status_is(terminal: str, status: str) -> bool:
    try:
        completed = subprocess.run([pairmux_bin(), "--json", "peek", terminal], text=True,
                                   encoding="utf-8", errors="replace", capture_output=True,
                                   timeout=60, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return f'"status":"{status}"' in completed.stdout


def _transcript(path: str | None) -> str | None:
    if not path or not Path(path).is_file():
        return None
    return Path(path).read_text(encoding="utf-8", errors="replace")


def _search(pattern: str, text: str) -> bool:
    return re.search(pattern, text, re.IGNORECASE | re.MULTILINE) is not None


def transcript_forbids(transcript: str | None, pattern: str) -> bool:
    """True unless the (Python) regex appears in the transcript; no transcript = outcome-only."""
    text = _transcript(transcript)
    return text is None or not _search(pattern, text)


def transcript_requires(transcript: str | None, pattern: str) -> bool:
    text = _transcript(transcript)
    return text is None or _search(pattern, text)


# Claude stream-json transcripts intersperse what the agent ISSUED (assistant text and tool_use
# inputs) with what the environment ECHOED BACK (tool_results). A fixture file legitimately read by
# the agent lands verbatim in a tool_result; that is not agent behavior. Assertions about what the
# agent did (leaked a secret, typed a command) therefore only see issued content.

def transcript_is_json(transcript: str | None) -> bool:
    if not transcript or not Path(transcript).is_file():
        return False
    with open(transcript, "rb") as handle:
        return handle.read(1) == b"{"


def _jq_tostring(value: object) -> str:
    """jq's `tostring`: strings verbatim, anything else as compact JSON (non-ASCII unescaped)."""
    if isinstance(value, str):
        return value
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def issued_content(transcript: str) -> str:
    """Agent-issued content only: Claude assistant text + tool_use inputs, OpenCode tool input and
    text events, Codex command strings and agent messages. Plain text uses the whole file."""
    if not transcript_is_json(transcript):
        return Path(transcript).read_text(encoding="utf-8", errors="replace")
    out: list[str] = []
    with open(transcript, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            if not isinstance(event, dict):
                continue
            kind = event.get("type")
            if kind == "assistant":
                for block in (event.get("message") or {}).get("content") or []:
                    if not isinstance(block, dict):
                        continue
                    if block.get("type") == "tool_use":
                        out.append(_jq_tostring(block.get("input", {})))
                    elif block.get("type") == "text":
                        out.append(str(block.get("text", "")))
            elif kind == "tool_use" and (event.get("part") or {}).get("type") == "tool":
                value = ((event.get("part") or {}).get("state") or {}).get("input")
                if value is not None:
                    out.append(_jq_tostring(value))
            elif kind == "text":
                out.append(str((event.get("part") or {}).get("text", "")))
            elif kind in {"item.started", "item.completed"}:
                item = event.get("item") or {}
                if item.get("type") == "command_execution":
                    out.append(str(item.get("command", "")))
                elif kind == "item.completed" and item.get("type") == "agent_message":
                    out.append(str(item.get("text", "")))
    return "\n".join(out)


def issued_forbids(transcript: str | None, pattern: str) -> bool:
    if not transcript or not Path(transcript).is_file():
        return True
    return not _search(pattern, issued_content(transcript))


def issued_requires(transcript: str | None, pattern: str) -> bool:
    if not transcript or not Path(transcript).is_file():
        return True
    return _search(pattern, issued_content(transcript))


def runner_trace_proves(scenario: str) -> bool:
    """In automated runs, require runner-owned exact-call proof. Manual runs have no proof path."""
    proof_path = os.environ.get("PAIRMUX_EVAL_TRACE_PROOF", "")
    if not proof_path:
        return True
    try:
        proof = json.loads(Path(proof_path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    return (isinstance(proof, dict)
            and set(proof) == {"schema", "scenario", "valid", "errors"}
            and proof.get("schema") == "pairmux.eval.trace-proof.v1"
            and proof.get("scenario") == scenario
            and proof.get("valid") is True
            and proof.get("errors") == [])


# ---- subgoal scoring (M suite) ------------------------------------------------------------------
# M-suite checks score fractionally: record each subgoal, then finish. The ledger lands in
# $PAIRMUX_EVAL_SUBGOALS_FILE (auto runs) or <scenario>/subgoals.json (manual runs); the runner
# turns it into the episode's score. Assertions must be harness-agnostic: task artifacts only.

class Subgoals:
    def __init__(self) -> None:
        self.entries: list[dict[str, object]] = []

    def add(self, subgoal_id: str, ok: object, detail: str = "") -> None:
        passed_ = ok is True or ok == 1 or ok == "1"
        self.entries.append({"id": subgoal_id, "pass": passed_, "detail": detail})
        print(f"subgoal PASS: {subgoal_id}" if passed_
              else f"subgoal FAIL: {subgoal_id}" + (f" — {detail}" if detail else ""), flush=True)

    def finish(self) -> None:
        out = os.environ.get("PAIRMUX_EVAL_SUBGOALS_FILE") or str(
            Path(os.environ.get("PAIRMUX_EVAL_SCENARIO_DIR") or ".") / "subgoals.json")
        payload = {"schema": "pairmux.eval.subgoals.v1", "subgoals": self.entries}
        with open(out, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(json.dumps(payload, indent=2) + "\n")
        count = sum(1 for entry in self.entries if entry["pass"])
        print(f"score: {count}/{len(self.entries)}", flush=True)
        raise SystemExit(0 if self.entries and count == len(self.entries) else 1)


# ---- small shared utilities ---------------------------------------------------------------------

def sha256_file(path: str | os.PathLike[str]) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def wait_until(predicate, timeout: float, message: str, interval: float = 0.05):
    """Poll a fixture-owned logical condition (control-plane coordination, never scoring)."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        result = predicate()
        if result:
            return result
        time.sleep(interval)
    raise SystemExit(message)


# A fixed sleep used to guess timing. Windows adds PowerShell's Start-Sleep and cmd's timeout.
SLEEP_GUESS = r"(^|\W)sleep\s+[0-9]" + (
    r"|(^|\W)start-sleep(\s+-(s|seconds|milliseconds|m))?\s+[0-9]|(^|\W)timeout(\.exe)?\s+/t\s+[0-9]"
    if IS_WINDOWS else "")


def read_answer(path: str | os.PathLike[str]) -> str:
    """An answer file's text. POSIX: exact UTF-8. Windows: also accept what native tools write
    (a UTF-8/UTF-16 byte-order mark, UTF-16 from PowerShell 5.1 redirection, CRLF line ends)."""
    data = Path(path).read_bytes()
    if not IS_WINDOWS:
        return data.decode("utf-8")
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        text = data.decode("utf-16")
    else:
        text = data.decode("utf-8-sig")
    return text.replace("\r\n", "\n")


# ---- per-platform fixtures ----------------------------------------------------------------------
# A scenario may carry a windows/ overlay: Windows twins of POSIX shell fixtures (same behavior,
# run as `python NAME.py`) and an optional windows/TASK.md whose wording does not assume bash.
# POSIX never sees the overlay, so macOS/Linux episodes are unchanged. On Windows the agent's
# worktree drops *.sh (there is no POSIX shell to run them) and gains the overlay files.

WINDOWS_OVERLAY = "windows"


def task_path(source_dir: Path) -> Path:
    override = Path(source_dir) / WINDOWS_OVERLAY / "TASK.md"
    return override if IS_WINDOWS and override.is_file() else Path(source_dir) / "TASK.md"


def overlay_files(source_dir: Path) -> list[Path]:
    overlay = Path(source_dir) / WINDOWS_OVERLAY
    if not IS_WINDOWS or not overlay.is_dir():
        return []
    return sorted(path for path in overlay.iterdir() if path.is_file() and path.name != "TASK.md")


def prepare_fixtures(script_file: str, scen_dir: Path, *, terminal_support: bool = False) -> None:
    """Materialize this platform's fixtures in scen_dir (setup calls it before hashing fixtures).
    On Windows copy the overlay twins in; optionally install the live-terminal helper."""
    source = script_dir(script_file)
    for path in overlay_files(source):
        target = Path(scen_dir) / path.name
        if path.resolve() != target.resolve():
            shutil.copy2(path, target)
    if terminal_support:
        shutil.copy2(EVALS_DIR / "termsupport.py", Path(scen_dir) / "termsupport.py")


def fixture_name(posix_name: str) -> str:
    """The name the agent runs: a POSIX `x.sh` fixture is `x.py` on Windows."""
    if IS_WINDOWS and posix_name.endswith(".sh"):
        return posix_name[:-3] + ".py"
    return posix_name


def platform_only(posix: bool = True, windows: bool = True) -> bool:
    return windows if IS_WINDOWS else posix


# A live terminal's recorded name: /dev/ttys* on POSIX, termsupport's console:<pid> on Windows.
TTY_PREFIX = "console:" if IS_WINDOWS else "/dev/"


def same_path(recorded: object, expected: str | os.PathLike[str]) -> bool:
    """A fixture-recorded path (cwd, sys.prefix) equals an expected one. POSIX: the exact string,
    as always. Windows: the same file-system location, ignoring case and 8.3 short names."""
    if not isinstance(recorded, str):
        return False
    if not IS_WINDOWS:
        return recorded == str(expected)
    try:
        return (os.path.normcase(os.path.realpath(recorded))
                == os.path.normcase(os.path.realpath(str(expected))))
    except (OSError, ValueError):
        return False
