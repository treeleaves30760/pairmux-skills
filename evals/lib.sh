#!/usr/bin/env bash
# Shared helpers for pairmux-skills evals. Sourced by every scenario's setup.sh and check.sh.
# Not meant to be executed directly.

# Resolve the pairmux binary: honor an explicit runner value, then PATH, then a sibling build.
pmx_resolve_bin() {
  local configured
  for configured in "${PAIRMUX_REAL_BIN:-}" "${PAIRMUX_BIN:-}"; do
    if [ -n "$configured" ] && [ -x "$configured" ]; then
      printf '%s\n' "$configured"
      return 0
    fi
  done
  if command -v pairmux >/dev/null 2>&1; then
    command -v pairmux
    return 0
  fi
  local libdir candidate
  libdir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  for candidate in \
    "$libdir/../../pairmux/bin/pairmux" \
    "$libdir/../../../pairmux/bin/pairmux"; do
    if [ -x "$candidate" ]; then
      ( cd "$(dirname "$candidate")" >/dev/null 2>&1 && printf '%s/pairmux\n' "$PWD" )
      return 0
    fi
  done
  return 1
}

# pmx_setup <scenario_dir> <id>
# Writes $PAIRMUX_EVAL_ENV_FILE (or <scenario_dir>/env.sh), then sources it, then resets state.
# After this returns, PAIRMUX_SOCKET / PAIRMUX_STATE_DIR / PATH / PAIRMUX_BIN are exported here.
pmx_setup() {
  local scen_dir="$1" id="$2" bin bindir state sock tmux_tmp namespace env_file control_root
  bin="$(pmx_resolve_bin)" || {
    echo "error: pairmux binary not found. Install pairmux, or build the sibling ../pairmux repo." >&2
    return 1
  }
  bindir="$(cd "$(dirname "$bin")" && pwd)"
  state="${PAIRMUX_EVAL_STATE_DIR:-$scen_dir/state}"
  env_file="${PAIRMUX_EVAL_ENV_FILE:-$scen_dir/env.sh}"
  control_root="${PAIRMUX_EVAL_CONTROL_ROOT:-}"
  sock="${PAIRMUX_EVAL_SOCKET:-pmx-eval-$id}"
  tmux_tmp="${TMPDIR:-/tmp}"
  namespace="$(pmx_state_namespace "$state" "$sock" "$tmux_tmp")"
  if ! python3 - "$state" "$scen_dir" "$control_root" <<'PY'
from pathlib import Path
import sys

state = Path(sys.argv[1]).expanduser().resolve()
scenario = Path(sys.argv[2]).resolve()
control = Path(sys.argv[3]).resolve() if sys.argv[3] else None
allowed = {scenario / "state"}
if control:
    allowed.add(control / "runtime" / "state")
if state not in {path.resolve() for path in allowed}:
    print(f"error: refusing to reset unexpected eval state directory: {state}", file=sys.stderr)
    raise SystemExit(1)
PY
  then
    return 1
  fi
  mkdir -p "$(dirname "$env_file")"
  python3 - "$sock" "$state" "$tmux_tmp" "$bindir" "$bin" "$namespace" >"$env_file" <<'PY'
import shlex
import sys

sock, state, tmux_tmp, bindir, pairmux_bin, namespace = sys.argv[1:]

print("# shellcheck shell=sh")
print("# Generated by setup.sh. Source this before launching the agent, and check.sh sources it too.")
for name, value in (
    ("PAIRMUX_SOCKET", sock),
    ("PAIRMUX_STATE_DIR", state),
    ("TMUX_TMPDIR", tmux_tmp),
    ("PAIRMUX_BIN", pairmux_bin),
    ("PAIRMUX_STATE_NAMESPACE", namespace),
):
    print(f"export {name}={shlex.quote(value)}")
print(f"export PATH={shlex.quote(bindir)}:\"$PATH\"")
print('if [ -n "${PAIRMUX_EVAL_PROXY_DIR:-}" ]; then')
print('  export PATH="${PAIRMUX_EVAL_PROXY_DIR}:$PATH"')
print("fi")
print('if [ -n "${PAIRMUX_EVAL_PROXY_BIN:-}" ]; then')
print('  export PAIRMUX_BIN="$PAIRMUX_EVAL_PROXY_BIN"')
print("fi")
PY
  # shellcheck source=/dev/null
  . "$env_file"
  tmux -L "$PAIRMUX_SOCKET" kill-server >/dev/null 2>&1 || true
  rm -rf -- "$state"
  mkdir -p "$state"
}

# ---- check.sh helpers -------------------------------------------------------

pmx_fail() { echo "FAIL: $*" >&2; exit 1; }
pmx_pass() { echo "PASS${1:+: $1}"; exit 0; }

pmx_bin() { printf '%s' "${PAIRMUX_BIN:-pairmux}"; }

# pmx_state_namespace <state-root> <socket> [tmux-tmpdir] — mirror pairmux's endpoint identity.
# The namespace key is sha256(canonical-TMUX_TMPDIR/tmux-UID/normalized-socket). On macOS the
# canonicalization intentionally resolves /tmp to /private/tmp, matching Go filepath.EvalSymlinks.
pmx_state_namespace() {
  local state_root="$1" socket="${2:-pairmux}" tmux_tmp="${3:-${TMUX_TMPDIR:-/tmp}}"
  python3 - "$state_root" "$socket" "$tmux_tmp" <<'PY'
import hashlib
import os
import sys

state_root, socket, tmux_tmp = sys.argv[1:]
socket = socket or "pairmux"
root = os.path.normpath(os.path.abspath(tmux_tmp or "/tmp"))
if os.path.exists(root):
    root = os.path.realpath(root)
identity = os.path.join(root, f"tmux-{os.getuid()}", socket)
print(os.path.join(state_root, ".sockets", hashlib.sha256(identity.encode()).hexdigest()))
PY
}

# pmx_terminal_dir <terminal> — locate one terminal under either state layout.
# Prefer pairmux's advertised namespace, otherwise reproduce its endpoint hash. The legacy fallback
# keeps the evals working against pre-namespace releases and the conventional default endpoint.
pmx_terminal_dir() {
  local terminal="$1" legacy namespace scoped
  legacy="$PAIRMUX_STATE_DIR/$terminal"
  if [ -n "${PAIRMUX_STATE_NAMESPACE:-}" ]; then
    scoped="$PAIRMUX_STATE_NAMESPACE/$terminal"
    if [ -d "$scoped" ]; then
      printf '%s\n' "$scoped"
      return 0
    fi
  fi
  if [ -d "$legacy" ]; then
    printf '%s\n' "$legacy"
    return 0
  fi
  if [ -n "${PAIRMUX_SOCKET:-}" ] && command -v python3 >/dev/null 2>&1; then
    namespace="$(pmx_state_namespace "$PAIRMUX_STATE_DIR" "$PAIRMUX_SOCKET")"
    scoped="$namespace/$terminal"
    if [ -d "$scoped" ]; then
      printf '%s\n' "$scoped"
      return 0
    fi
  fi
  printf '%s\n' "$legacy"
}

# pmx_journal_has <terminal> <literal-needle>  — true if that terminal's raw.log contains the needle.
pmx_journal_has() {
  local f
  f="$(pmx_terminal_dir "$1")/raw.log"
  [ -f "$f" ] && grep -qF -- "$2" "$f"
}

# pmx_any_journal_has <literal-needle> — true if ANY terminal's raw.log contains the needle.
pmx_any_journal_has() {
  local needle="$1" f
  for f in "${PAIRMUX_STATE_NAMESPACE:-/nonexistent}"/*/raw.log \
    "$PAIRMUX_STATE_DIR"/*/raw.log "$PAIRMUX_STATE_DIR"/.sockets/*/*/raw.log; do
    [ -f "$f" ] || continue
    grep -qF -- "$needle" "$f" && return 0
  done
  return 1
}

# pmx_index_has <terminal> <literal-needle> — true if that terminal's index.jsonl contains the needle.
pmx_index_has() {
  local f
  f="$(pmx_terminal_dir "$1")/index.jsonl"
  [ -f "$f" ] && grep -qF -- "$2" "$f"
}

# pmx_status_is <terminal> <status> — true if `peek` reports that status.
pmx_status_is() {
  "$(pmx_bin)" --json peek "$1" 2>/dev/null | grep -q "\"status\":\"$2\""
}

# pmx_transcript_forbids <transcript> <ERE> — true unless the ERE appears in the transcript file.
# A missing/empty transcript path means "nothing to check" (outcome-only mode) and returns true.
pmx_transcript_forbids() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  ! grep -Eqi -- "$pat" "$t"
}

# pmx_transcript_requires <transcript> <ERE> — true if the ERE appears, OR no transcript was provided.
pmx_transcript_requires() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  grep -Eqi -- "$pat" "$t"
}

# ---- agent-ISSUED transcript scoping ----------------------------------------
# Claude stream-json transcripts intersperse what the agent ISSUED (assistant text and tool_use
# inputs) with what the environment ECHOED BACK (tool_results). A fixture file legitimately read
# by the agent lands verbatim in a tool_result — that is not agent behavior. Assertions about what
# the agent did (leaked a secret, typed a command) must therefore only see issued content.

# pmx_transcript_is_json <transcript> — true if the file looks like (stream-)JSON.
pmx_transcript_is_json() {
  local t="$1"
  [ -n "$t" ] && [ -f "$t" ] && [ "$(head -c 1 "$t" 2>/dev/null)" = "{" ]
}

# pmx_issued_content <transcript> — print agent-issued content only.
# * Claude stream-json: assistant text blocks + tool_use inputs, extracted with jq.
# * OpenCode JSON: tool input and assistant text events, excluding tool output/fixture echoes.
# * Codex JSONL: command_execution command strings and agent_message text, excluding aggregated output.
# Python is the structured fallback when jq is absent; plain text uses the whole file.
pmx_issued_content() {
  local t="$1"
  if pmx_transcript_is_json "$t"; then
    if command -v jq >/dev/null 2>&1; then
      jq -r 'if .type=="assistant" then
               .message.content[]?
               | if .type=="tool_use" then (.input|tostring)
                 elif .type=="text" then .text
                 else empty end
             elif .type=="tool_use" and .part.type=="tool" then
               (.part.state.input // empty | tostring)
             elif .type=="text" then
               (.part.text // empty)
             elif (.type=="item.started" or .type=="item.completed")
                  and .item.type=="command_execution" then
               (.item.command // empty)
             elif .type=="item.completed" and .item.type=="agent_message" then
               (.item.text // empty)
             else empty end' "$t" 2>/dev/null
    elif command -v python3 >/dev/null 2>&1; then
      python3 - "$t" <<'PY'
import json
import sys

for line in open(sys.argv[1], encoding="utf-8"):
    try:
        event = json.loads(line)
    except json.JSONDecodeError:
        continue
    kind = event.get("type")
    if kind == "assistant":
        for block in event.get("message", {}).get("content", []):
            if block.get("type") == "tool_use":
                print(json.dumps(block.get("input", {}), separators=(",", ":")))
            elif block.get("type") == "text":
                print(block.get("text", ""))
    elif kind == "tool_use" and event.get("part", {}).get("type") == "tool":
        value = event.get("part", {}).get("state", {}).get("input")
        if value is not None:
            print(json.dumps(value, separators=(",", ":")))
    elif kind == "text":
        print(event.get("part", {}).get("text", ""))
    elif kind in {"item.started", "item.completed"}:
        item = event.get("item", {})
        if item.get("type") == "command_execution":
            print(item.get("command", ""))
        elif kind == "item.completed" and item.get("type") == "agent_message":
            print(item.get("text", ""))
PY
    else
      grep -E -- '"type"[[:space:]]*:[[:space:]]*"(assistant|tool_use|text)"' "$t"
    fi
  else
    cat "$t"
  fi
}

# pmx_issued_forbids <transcript> <ERE> — true unless the ERE appears in agent-issued content.
# Missing/empty transcript path = outcome-only mode = true.
pmx_issued_forbids() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  ! pmx_issued_content "$t" | grep -Eqi -- "$pat"
}

# pmx_issued_requires <transcript> <ERE> — true if the ERE appears in agent-issued content, OR no
# transcript was provided (outcome-only mode).
pmx_issued_requires() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  pmx_issued_content "$t" | grep -Eqi -- "$pat"
}

# pmx_calls_has_human_wait <pairmux-calls.jsonl> — exact, interrupted argv proof of `wait --human`.
pmx_calls_has_human_wait() {
  local calls="$1"
  [ -n "$calls" ] && [ -f "$calls" ] || return 1
  python3 - "$calls" <<'PY'
import json
import sys

def effective_command(argv):
    if not isinstance(argv, list) or not all(isinstance(value, str) for value in argv):
        return None
    index = 0
    while index < len(argv):
        value = argv[index]
        if value == "--json":
            index += 1
        elif value == "--socket":
            index += 2
        elif value.startswith("--socket=") or value == "--":
            index += 1
        else:
            return value, argv[index + 1:]
    return None

for line in open(sys.argv[1], encoding="utf-8"):
    try:
        call = json.loads(line)
    except (json.JSONDecodeError, AttributeError):
        continue
    command = effective_command(call.get("argv"))
    interrupted = (
        call.get("harness_finalized") is True
        or isinstance(call.get("exit_code"), int) and call["exit_code"] < 0
        or isinstance(call.get("exit_signal"), int) and call["exit_signal"] > 0
        or isinstance(call.get("received_signals"), list) and bool(call["received_signals"])
    )
    if command and command[0] == "wait" and "--human" in command[1] and interrupted:
        raise SystemExit(0)
raise SystemExit(1)
PY
}

# pmx_runner_trace_proves <scenario> — in automated runs, require runner-owned exact-call proof.
# Manual runs have no proof path and retain their outcome-only behavior.
pmx_runner_trace_proves() {
  local scenario="$1" proof="${PAIRMUX_EVAL_TRACE_PROOF:-}"
  [ -n "$proof" ] || return 0
  [ -f "$proof" ] || return 1
  python3 - "$proof" "$scenario" <<'PY'
import json
import sys

try:
    proof = json.load(open(sys.argv[1], encoding="utf-8"))
except (OSError, json.JSONDecodeError):
    raise SystemExit(1)
valid = (
    set(proof) == {"schema", "scenario", "valid", "errors"}
    and proof.get("schema") == "pairmux.eval.trace-proof.v1"
    and proof.get("scenario") == sys.argv[2]
    and proof.get("valid") is True
    and proof.get("errors") == []
)
raise SystemExit(0 if valid else 1)
PY
}
