#!/usr/bin/env bash
# Shared helpers for pairmux-skills evals. Sourced by every scenario's setup.sh and check.sh.
# Not meant to be executed directly.

# Resolve the pairmux binary: prefer one on PATH, else the sibling `pairmux` repo's bin/.
pmx_resolve_bin() {
  if command -v pairmux >/dev/null 2>&1; then
    command -v pairmux
    return 0
  fi
  local libdir candidate
  libdir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  for candidate in \
    "$libdir/../../pairmux/bin/pairmux" \
    "$libdir/../../../pairmux/bin/pairmux"; do
    if [ -x "$candidate" ]; then
      ( cd "$(dirname "$candidate")" >/dev/null 2>&1 && printf '%s/pairmux\n' "$PWD" )
      return 0
    fi
  done
  return 1
}

# pmx_setup <scenario_dir> <id>
# Writes <scenario_dir>/env.sh, then sources it, then wipes and recreates the isolated state.
# After this returns, PAIRMUX_SOCKET / PAIRMUX_STATE_DIR / PATH / PAIRMUX_BIN are exported here.
pmx_setup() {
  local scen_dir="$1" id="$2" bin bindir state sock
  bin="$(pmx_resolve_bin)" || {
    echo "error: pairmux binary not found. Install pairmux, or build the sibling ../pairmux repo." >&2
    return 1
  }
  bindir="$(cd "$(dirname "$bin")" && pwd)"
  state="$scen_dir/state"
  sock="pmx-eval-$id"
  cat >"$scen_dir/env.sh" <<EOF
# shellcheck shell=sh
# Generated by setup.sh. Source this before launching the agent, and check.sh sources it too.
export PAIRMUX_SOCKET="$sock"
export PAIRMUX_STATE_DIR="$state"
export PATH="$bindir:\$PATH"
export PAIRMUX_BIN="$bin"
EOF
  # shellcheck source=/dev/null
  . "$scen_dir/env.sh"
  tmux -L "$PAIRMUX_SOCKET" kill-server >/dev/null 2>&1 || true
  rm -rf "$state"
  mkdir -p "$state"
}

# ---- check.sh helpers -------------------------------------------------------

pmx_fail() { echo "FAIL: $*" >&2; exit 1; }
pmx_pass() { echo "PASS${1:+: $1}"; exit 0; }

pmx_bin() { printf '%s' "${PAIRMUX_BIN:-pairmux}"; }

# pmx_journal_has <terminal> <literal-needle>  — true if that terminal's raw.log contains the needle.
pmx_journal_has() {
  local f="$PAIRMUX_STATE_DIR/$1/raw.log"
  [ -f "$f" ] && grep -qF -- "$2" "$f"
}

# pmx_any_journal_has <literal-needle> — true if ANY terminal's raw.log contains the needle.
pmx_any_journal_has() {
  local needle="$1" f
  for f in "$PAIRMUX_STATE_DIR"/*/raw.log; do
    [ -f "$f" ] || continue
    grep -qF -- "$needle" "$f" && return 0
  done
  return 1
}

# pmx_index_has <terminal> <literal-needle> — true if that terminal's index.jsonl contains the needle.
pmx_index_has() {
  local f="$PAIRMUX_STATE_DIR/$1/index.jsonl"
  [ -f "$f" ] && grep -qF -- "$2" "$f"
}

# pmx_status_is <terminal> <status> — true if `peek` reports that status.
pmx_status_is() {
  "$(pmx_bin)" --json peek "$1" 2>/dev/null | grep -q "\"status\":\"$2\""
}

# pmx_transcript_forbids <transcript> <ERE> — true unless the ERE appears in the transcript file.
# A missing/empty transcript path means "nothing to check" (outcome-only mode) and returns true.
pmx_transcript_forbids() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  ! grep -Eqi -- "$pat" "$t"
}

# pmx_transcript_requires <transcript> <ERE> — true if the ERE appears, OR no transcript was provided.
pmx_transcript_requires() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  grep -Eqi -- "$pat" "$t"
}

# ---- agent-ISSUED transcript scoping ----------------------------------------
# Claude stream-json transcripts intersperse what the agent ISSUED (assistant text and tool_use
# inputs) with what the environment ECHOED BACK (tool_results). A fixture file legitimately read
# by the agent lands verbatim in a tool_result — that is not agent behavior. Assertions about what
# the agent did (leaked a secret, typed a command) must therefore only see issued content.

# pmx_transcript_is_json <transcript> — true if the file looks like (stream-)JSON.
pmx_transcript_is_json() {
  local t="$1"
  [ -n "$t" ] && [ -f "$t" ] && [ "$(head -c 1 "$t" 2>/dev/null)" = "{" ]
}

# pmx_issued_content <transcript> — print agent-issued content only.
# * Claude stream-json (.jsonl): assistant text blocks + tool_use inputs, extracted with jq.
#   jq-less fallback: stream-json is one event per line and assistant events carry only issued
#   blocks (tool_results arrive as separate "user" events), so line-filtering scopes correctly too.
# * Plain text (codex exec): issued vs echoed content is not reliably separable, so the whole file
#   is used — a documented asymmetry that makes plain-text checks stricter than stream-json ones.
pmx_issued_content() {
  local t="$1"
  if pmx_transcript_is_json "$t"; then
    if command -v jq >/dev/null 2>&1; then
      jq -r 'select(.type=="assistant") | .message.content[]?
             | if .type=="tool_use" then (.input|tostring)
               elif .type=="text" then .text
               else empty end' "$t" 2>/dev/null
    else
      grep -- '"type":"assistant"' "$t"
    fi
  else
    cat "$t"
  fi
}

# pmx_issued_forbids <transcript> <ERE> — true unless the ERE appears in agent-issued content.
# Missing/empty transcript path = outcome-only mode = true.
pmx_issued_forbids() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  ! pmx_issued_content "$t" | grep -Eqi -- "$pat"
}

# pmx_issued_requires <transcript> <ERE> — true if the ERE appears in agent-issued content, OR no
# transcript was provided (outcome-only mode).
pmx_issued_requires() {
  local t="$1" pat="$2"
  [ -n "$t" ] && [ -f "$t" ] || return 0
  pmx_issued_content "$t" | grep -Eqi -- "$pat"
}
